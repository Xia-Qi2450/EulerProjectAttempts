        self.header(
            31,
            "Find the number of different ways can £2 be made using any number of coins?"
        )
        def task():
            target = 200
            coins = [1, 2, 5, 10, 20, 50, 100, 200]
            
            # dp[i] will store the number of ways to form a target sum 'i'
            dp = [1] + [0] * target
            
