    def problem35(self):
        "Find the number of circular primes are there below one million."
        self.header(
            35,
            "Find the number of circular primes are there below one million."
        )
        def task():
            limit = 1_000_000
            is_prime_lookup = self.sieve_of_eratosthenes_list(limit)
            circular_prime_count = 0
            invalid_digits = {'0', '2', '4', '5', '6', '8'}
